export function makeEventCtx(R, data) {
  return { level: (g) => R.profile.level(g), spouseGroup: data.meta.gender === '여' ? '관성' : '재성', gender: data.meta.gender, needEl: R.needEl, yongEl: R.yong.el, giEl: R.yong.gi };
}

/** 한 달(또는 한 해)의 사건 문장. range: "6월 6일~7월 6일" 같은 기간 문구(선택) */
export function eventFor({ g, cat, ctx, range, span = '월' }) {
  const catKey = cat && SHAPE[cat] ? cat : cat === '결혼' ? '연애' : '종합';
  const bg = grp(g.branchGod), sg = grp(g.stemGod);
  const isSpouse = (catKey === '연애') && (bg === ctx.spouseGroup || sg === ctx.spouseGroup);
  const main = isSpouse ? '배우자' : bg;
  const shape = SHAPE[catKey]?.[main]?.(g, ctx) || `${K.LUCK[g.branchGod]?.head || bg}이 중심이 되는 흐름이에요`;
  const when = range ? `${range} 사이` : span === '년' ? '이 해' : '이 달';
  const first = `${when}에는 ${shape}.`;
  const why = ` ${LEVEL_WHY(isSpouse ? `${ctx.spouseGroup}(배우자 별)` : bg, ctx.level(bg))}${sg && sg !== bg ? ` ${span === '년' ? '상반기·겉으로는' : '초반·겉으로는'} 천간 ${g.stem}의 ${sg} 기운으로 시작해 ${span === '년' ? '하반기·속으로는' : '중순 이후·속으로는'} 지지 ${g.branch}의 ${bg}이 실속을 만들어요.` : ''}`;
  const extras = [];
  if (has(g, '충', 'day')) extras.push(OVERLAY.dayChung[catKey] || OVERLAY.dayChung.종합);
  else if (has(g, '충', 'month')) extras.push(OVERLAY.monthChung[catKey] || OVERLAY.monthChung.종합);
  if (has(g, '합', 'day') || has(g, '합', 'month') || has(g, '삼합')) extras.push(OVERLAY.hap[catKey] || OVERLAY.hap.종합);
  if (['역마', '지살'].includes(g.sal)) extras.push(OVERLAY.yeokma[catKey] || OVERLAY.yeokma.종합);
  if (g.sal === '년살') extras.push(OVERLAY.dohwa[catKey] || OVERLAY.dohwa.종합);
  if (g.luck?.isGong) extras.push(OVERLAY.gong);
  if (g.luck?.hasNeed) extras.push(OVERLAY.need(ctx.needEl));
  else if (g.luck?.hasYong) extras.push(OVERLAY.yong(ctx.yongEl));
  if (g.luck?.hasGi) extras.push(OVERLAY.gi(ctx.giEl));
  if (g.dyn?.helps?.length) extras.push(`타고난 약한 고리인 "${g.dyn.helps[0].title}"를 이때 채워 줘요 — ${g.dyn.helps[0].text}`);
  else if (g.dyn?.hurts?.length) extras.push(`반대로 "${g.dyn.hurts[0].title}"는 이때 더 도드라져요 — ${g.dyn.hurts[0].text}`);
  return (first + why + (extras.length ? ' ' + extras.slice(0, 4).join(' ') : '')).replace(/\.\./g, '.').replace(/ +/g, ' ').trim();
}
