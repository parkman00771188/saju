export const isYangStem = (s) => STEMS.indexOf(s) % 2 === 0;
export const isYangBranch = (b) => BRANCHES.indexOf(b) % 2 === 0;

/** 일간 기준 십성 (target: 천간) */
export function tenGod(dayStem, target) {
  const de = STEM_ELEMENT[dayStem], te = STEM_ELEMENT[target];
  const same = isYangStem(dayStem) === isYangStem(target);
  if (de === te) return same ? '비견' : '비겁';
  if (GEN[de] === te) return same ? '식신' : '상관';
  if (CTRL[de] === te) return same ? '편재' : '정재';
  if (CTRL[te] === de) return same ? '편관' : '정관';
  if (GEN[te] === de) return same ? '편인' : '정인';
  return '';
}

