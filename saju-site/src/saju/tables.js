export function twelveStage(dayStem, branch) {
  const start = BRANCHES.indexOf(BIRTH_BRANCH[dayStem]);
  const cur = BRANCHES.indexOf(branch);
  const step = isYangStem(dayStem) ? (cur - start + 12) % 12 : (start - cur + 12) % 12;
  return TWELVE_STAGES[step];
}

