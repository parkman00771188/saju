COMPILED = [(re.compile(pattern), replacement) for pattern, replacement in FIXES]


def normalize(text, counter=None):
    """교정을 적용하고, counter가 있으면 패턴별 치환 횟수를 누적한다."""
    # 앞 규칙의 결과가 뒤 규칙의 교정 대상이 되는 경우가 있어 안정될 때까지
    # 최대 세 번 돈다. 모든 규칙은 한 방향 치환이라 순환하지 않는다.
    for _ in range(3):
        before = text
        for regex, replacement in COMPILED:
            if counter is None:
                text = regex.sub(replacement, text)
                continue

            def replace(match, *, _replacement=replacement, _pattern=regex.pattern):
                value = match.expand(_replacement) if isinstance(_replacement, str) else _replacement(match)
                if value != match.group(0):
                    counter[_pattern] = counter.get(_pattern, 0) + 1
                return value

            text = regex.sub(replace, text)
        if text == before:
            break
    return text
