COMPILED = [(re.compile(p), r) for p, r in FIXES]


def normalize(text, counter=None):
    """교정 적용. counter(dict)가 주어지면 패턴별 치환 횟수를 누적한다."""
    for rx, rep in COMPILED:
        if counter is not None:
            text, n = rx.subn(rep, text)
            if n:
                counter[rx.pattern] = counter.get(rx.pattern, 0) + n
        else:
            text = rx.sub(rep, text)
    return text
